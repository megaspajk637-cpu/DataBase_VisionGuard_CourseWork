DROP SCHEMA IF EXISTS VisionGuard CASCADE;
CREATE SCHEMA VisionGuard;

CREATE TABLE VisionGuard.Camera (
    camera_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_camera PRIMARY KEY (camera_id),
    name VARCHAR(100) UNIQUE NOT NULL,
    location TEXT NOT NULL,
    rtsp_url TEXT NOT NULL,
    status VARCHAR(12) NOT NULL,
    CONSTRAINT camera_status_check CHECK (status IN('online', 'offline', 'maintenance')),
    installed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE VisionGuard.Operator (
    operator_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_operator PRIMARY KEY (operator_id),
    email VARCHAR(256) NOT NULL UNIQUE,
    CONSTRAINT operator_email_check CHECK (email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    full_name VARCHAR(160) NOT NULL,
    CONSTRAINT operator_full_name_check CHECK (length(btrim(full_name)) > 0),
    role VARCHAR(20) NOT NULL,
    CONSTRAINT operator_role_check CHECK (role IN ('admin', 'supervisor', 'operator', 'analyst', 'engineer')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE VisionGuard.ML_model(
    model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_key TEXT NOT NULL,
    version TEXT NOT NULL,
    task TEXT NOT NULL,
    accuracy NUMERIC(4,3) NOT NULL,
    CONSTRAINT chk_ml_model_accuracy CHECK(accuracy BETWEEN 0 AND 1),
    valid_from TIMESTAMPTZ NOT NULL,
    valid_to TIMESTAMPTZ,
    CONSTRAINT uq_ml_model_version UNIQUE (model_key, version),
    CONSTRAINT chk_ml_model_valid_to CHECK(valid_to IS NULL OR valid_to > valid_from)
);
CREATE UNIQUE INDEX idx_ml_model_current ON VisionGuard.ML_model (model_key) WHERE valid_to IS NULL;

CREATE TABLE VisionGuard.Zone(
    zone_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_zone PRIMARY KEY (zone_id),
    name VARCHAR(100) NOT NULL UNIQUE,
    zone_type VARCHAR(20) NOT NULL,
    CONSTRAINT zone_type_check CHECK(zone_type IN('danger', 'entrance', 'parking', 'perimeter')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE VisionGuard.Detection_rule (
    rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_detection_rule PRIMARY KEY (rule_id),
    rule_key VARCHAR(100) NOT NULL,
    CONSTRAINT detection_rule_key_check CHECK (length(btrim(rule_key)) > 0),
    version INTEGER NOT NULL,
    CONSTRAINT detection_rule_version_check CHECK (version >= 1),
    object_class VARCHAR(100) NOT NULL,
    CONSTRAINT detection_rule_object_class_check CHECK (object_class IN ('person', 'car')),
    zone_type VARCHAR(20) NOT NULL,
    CONSTRAINT detection_rule_zone_type_check CHECK (zone_type IN ('danger', 'entrance', 'parking', 'perimeter')),
    min_confidence NUMERIC(4,3) NOT NULL,
    CONSTRAINT detection_rule_confidence_check CHECK (min_confidence >= 0 AND min_confidence <= 1),
    critically VARCHAR(16) NOT NULL,
    CONSTRAINT detection_rule_critically_check CHECK (critically IN ('low', 'medium', 'high', 'critical')),
    priority SMALLINT NOT NULL DEFAULT 100,
    CONSTRAINT detection_rule_priority_check CHECK (priority >= 0),
    valid_from TIMESTAMPTZ NOT NULL,
    valid_to TIMESTAMPTZ,
    CONSTRAINT detection_rule_dates_check CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT detection_rule_rule_version_unique UNIQUE (rule_key, version)
);
CREATE UNIQUE INDEX uq_rule_current ON VisionGuard.Detection_rule (rule_key) WHERE valid_to IS NULL;

CREATE TABLE VisionGuard.Camera_status_log(
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id BIGINT NOT NULL,
    CONSTRAINT fk_camera_status_log_camera FOREIGN KEY (camera_id) REFERENCES VisionGuard.Camera(camera_id) ON DELETE RESTRICT,
    old_status VARCHAR(12) NOT NULL,
    CONSTRAINT chk_camera_status_log_old_status CHECK(old_status IN('online', 'offline', 'maintenance')),
    new_status VARCHAR(12) NOT NULL,
    CONSTRAINT chk_camera_status_log_new_status CHECK(new_status IN('online', 'offline', 'maintenance')),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_camera_status_log_status_change CHECK(old_status <> new_status)
);

CREATE TABLE VisionGuard.Camera_day_statistics(
    camera_id BIGINT NOT NULL,
    CONSTRAINT fk_camera_day_statistics_camera FOREIGN KEY (camera_id) REFERENCES VisionGuard.Camera(camera_id) ON DELETE RESTRICT,
    statistics_date DATE NOT NULL,
    event_count INTEGER NOT NULL,
    CONSTRAINT chk_camera_day_statistics_event_count CHECK(event_count >= 0),
    alert_count INTEGER NOT NULL,
    CONSTRAINT chk_camera_day_statistics_alert_count CHECK(alert_count >= 0),
    people_count INTEGER NOT NULL,
    CONSTRAINT chk_camera_day_statistics_people_count CHECK(people_count >= 0),
    car_count INTEGER NOT NULL,
    CONSTRAINT chk_camera_day_statistics_car_count CHECK(car_count >= 0),
    average_confidence NUMERIC(4,3),
    CONSTRAINT chk_camera_day_statistics_confidence CHECK(average_confidence BETWEEN 0 AND 1),
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (camera_id, statistics_date),
    CONSTRAINT chk_camera_day_statistics_event_confidence CHECK((event_count = 0 AND average_confidence IS NULL) OR (event_count > 0 AND average_confidence IS NOT NULL))
);

CREATE TABLE VisionGuard.Camera_zone(
    camera_zone_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_camera_zone PRIMARY KEY (camera_zone_id),
    camera_id BIGINT NOT NULL,
    CONSTRAINT foreign_key_cam_zone_camera FOREIGN KEY (camera_id) REFERENCES VisionGuard.Camera(camera_id) ON DELETE RESTRICT,
    zone_id BIGINT NOT NULL,
    CONSTRAINT foreign_key_cam_zone_zone FOREIGN KEY (zone_id) REFERENCES VisionGuard.Zone(zone_id) ON DELETE RESTRICT,
    polygon_json JSONB NOT NULL,
    CONSTRAINT polygon_json_check CHECK(jsonb_typeof(polygon_json) = 'array'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE VisionGuard.Shift (
    shift_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_shift PRIMARY KEY (shift_id),
    operator_id BIGINT NOT NULL,
    CONSTRAINT foreign_key_shift_operator FOREIGN KEY (operator_id) REFERENCES VisionGuard.Operator(operator_id) ON DELETE RESTRICT,
    camera_id BIGINT NOT NULL,
    CONSTRAINT foreign_key_shift_camera FOREIGN KEY (camera_id) REFERENCES VisionGuard.Camera(camera_id) ON DELETE RESTRICT,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    CONSTRAINT shift_dates_check CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE VisionGuard.Detection_event(
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT primary_key_detection_event PRIMARY KEY (event_id),
    camera_zone_id BIGINT NOT NULL,
    CONSTRAINT foreign_key_det_event_cam_zone FOREIGN KEY (camera_zone_id) REFERENCES VisionGuard.Camera_zone(camera_zone_id) ON DELETE RESTRICT,
    model_id BIGINT NOT NULL,
    CONSTRAINT foreign_key_det_event_model FOREIGN KEY (model_id) REFERENCES VisionGuard.ML_model(model_id) ON DELETE RESTRICT,
    captured_at TIMESTAMPTZ NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL,
    object_class VARCHAR(100) NOT NULL,
    CONSTRAINT object_class_check CHECK(object_class IN('person', 'car')),
    confidence NUMERIC(4,3) NOT NULL,
    CONSTRAINT confidence_check CHECK(confidence >= 0 AND confidence <= 1),
    track_id VARCHAR(100),
    box_json JSONB,
    CONSTRAINT box_json_check CHECK(box_json IS NULL OR jsonb_typeof(box_json) = 'array'),
    CONSTRAINT interval_check CHECK(captured_at < detected_at)
);

CREATE TABLE VisionGuard.alert (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NULL,
    CONSTRAINT fk_alert_rule FOREIGN KEY (rule_id) REFERENCES VisionGuard.Detection_rule(rule_id) ON DELETE RESTRICT,
    event_id BIGINT NULL UNIQUE,
    CONSTRAINT fk_alert_event FOREIGN KEY (event_id) REFERENCES VisionGuard.Detection_event(event_id) ON DELETE RESTRICT,
    operator_id BIGINT NULL,
    CONSTRAINT fk_alert_operator FOREIGN KEY (operator_id) REFERENCES VisionGuard.Operator(operator_id) ON DELETE RESTRICT,
    critically VARCHAR(12) NOT NULL,
    CONSTRAINT chk_alert_critically CHECK (critically IN ('low', 'medium', 'high', 'critical')),
    status VARCHAR(12) NOT NULL DEFAULT 'open',
    CONSTRAINT chk_alert_status CHECK (status IN ('open', 'acknowledged', 'resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT chk_alert_closed_at_date CHECK (closed_at IS NULL OR closed_at > created_at),
    CONSTRAINT chk_alert_closed_status CHECK ((status = 'resolved' AND closed_at IS NOT NULL) OR (status <> 'resolved' AND closed_at IS NULL)),
    alert_source VARCHAR(10) NOT NULL,
    CONSTRAINT chk_alert_source_type CHECK (alert_source IN ('automatic', 'manual')),
    CONSTRAINT chk_alert_source CHECK (alert_source = 'manual' OR (rule_id IS NOT NULL AND event_id IS NOT NULL))
);

CREATE TABLE VisionGuard.alert_comment (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id BIGINT NOT NULL,
    CONSTRAINT fk_alert_comment_operator FOREIGN KEY (operator_id) REFERENCES VisionGuard.Operator(operator_id) ON DELETE RESTRICT,
    alert_id BIGINT NOT NULL,
    CONSTRAINT fk_alert_comment_alert_id FOREIGN KEY (alert_id) REFERENCES VisionGuard.alert(alert_id) ON DELETE RESTRICT,
    comment_text TEXT NOT NULL,
    CONSTRAINT chk_comment_text CHECK (length(trim(comment_text)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE VisionGuard.alert_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL,
    CONSTRAINT fk_alert_history_alert_id FOREIGN KEY (alert_id) REFERENCES VisionGuard.alert(alert_id) ON DELETE RESTRICT,
    operator_id BIGINT NOT NULL,
    CONSTRAINT fk_alert_history_operator_id FOREIGN KEY (operator_id) REFERENCES VisionGuard.Operator(operator_id) ON DELETE RESTRICT,
    old_status VARCHAR(12) NOT NULL,
    CONSTRAINT chk_alert_history_old_status CHECK (old_status IN ('open', 'acknowledged', 'resolved')),
    new_status VARCHAR(12) NOT NULL,
    CONSTRAINT chk_alert_history_new_status CHECK (new_status IN ('open', 'acknowledged', 'resolved')),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_history_status_change CHECK (old_status <> new_status)
);